// Writes the design tokens: tokens.json (Design Tokens Community Group format), tokens.css,
// and Starlight themes the docs sites can drop in.
import fs from 'node:fs';
import path from 'node:path';
import { neutrals, scales, templates } from './brand.mjs';

export const fontStacks = {
  display: ["'Bricolage Grotesque Variable'", "'Bricolage Grotesque'", 'ui-sans-serif', 'system-ui', 'sans-serif'],
  body: ["'Inter Variable'", "'Inter'", 'ui-sans-serif', 'system-ui', 'sans-serif'],
  mono: ["'JetBrains Mono Variable'", "'JetBrains Mono'", 'ui-monospace', 'monospace'],
};

const header = (what) => `/* ${what}\n * Generated by scripts/build.mjs from scripts/brand.mjs. Edit those, not this file. */\n`;

export function writeTokens(dir) {
  fs.mkdirSync(path.join(dir, 'starlight'), { recursive: true });

  const color = { ink: { $type: 'color', $value: neutrals.ink }, paper: { $type: 'color', $value: neutrals.paper } };
  for (const [name, scale] of Object.entries(scales)) {
    color[name] = Object.fromEntries(Object.entries(scale).map(([step, hex]) => [step, { $type: 'color', $value: hex }]));
  }
  const template = Object.fromEntries(
    templates.map((t) => [t.key, { $description: `${t.name}${t.reserved ? ' (reserved)' : ''}`, hue: { $type: 'color', $value: `{color.${t.hue}.500}` } }]),
  );
  template.org = { $description: 'Lean Mean Clean Apps', hue: { $type: 'color', $value: '{color.leaf.500}' } };
  const font = Object.fromEntries(Object.entries(fontStacks).map(([k, v]) => [k, { $type: 'fontFamily', $value: v.map((f) => f.replace(/'/g, '')) }]));
  fs.writeFileSync(path.join(dir, 'tokens.json'), JSON.stringify({ color, template, font }, null, 2) + '\n');

  const css = [header('Lean Mean Clean Apps design tokens.'), ':root {', `  --lmca-ink: ${neutrals.ink};`, `  --lmca-paper: ${neutrals.paper};`];
  for (const [name, scale] of Object.entries(scales)) for (const [step, hex] of Object.entries(scale)) css.push(`  --lmca-${name}-${step}: ${hex};`);
  css.push('');
  for (const t of templates) css.push(`  --lmca-${t.key}: var(--lmca-${t.hue}-500);${t.reserved ? ' /* reserved */' : ''}`);
  css.push('  --lmca-org: var(--lmca-leaf-500);', '');
  for (const [k, v] of Object.entries(fontStacks)) css.push(`  --lmca-font-${k}: ${v.join(', ')};`);
  css.push('}', '');
  fs.writeFileSync(path.join(dir, 'tokens.css'), css.join('\n'));

  // Shared Starlight base: ink dark mode, paper light mode, and the three typefaces.
  fs.writeFileSync(
    path.join(dir, 'starlight', 'base.css'),
    `${header('Starlight base theme for Lean Mean Clean Apps docs sites. Pair it with one accent file.')}
:root {
  --sl-font: ${fontStacks.body.join(', ')};
  --sl-font-mono: ${fontStacks.mono.join(', ')};
  --lmca-font-display: ${fontStacks.display.join(', ')};

  --sl-color-white: ${neutrals.paper};
  --sl-color-gray-1: #e9ecf2;
  --sl-color-gray-2: #c3cad8;
  --sl-color-gray-3: #8c96ad;
  --sl-color-gray-4: #5a6480;
  --sl-color-gray-5: #2a3554;
  --sl-color-gray-6: #141d38;
  --sl-color-black: ${neutrals.ink};
}

:root[data-theme='light'] {
  --sl-color-white: ${neutrals.ink};
  --sl-color-gray-1: #1c2838;
  --sl-color-gray-2: #2f3b52;
  --sl-color-gray-3: #535d78;
  --sl-color-gray-4: #8c96ad;
  --sl-color-gray-5: #d9dce3;
  --sl-color-gray-6: #efede6;
  --sl-color-gray-7: #f6f4ef;
  --sl-color-black: ${neutrals.paper};
}

.sl-markdown-content :is(h1, h2, h3),
h1#_top,
.hero h1,
.site-title {
  font-family: var(--lmca-font-display);
  letter-spacing: -0.02em;
}

code,
pre {
  font-variant-ligatures: none;
}
`,
  );

  // One accent file per template, plus one for the organisation.
  const accents = [...templates.map((t) => [t.key, t.name, t.hue]), ['org', 'Lean Mean Clean Apps', 'leaf']];
  for (const [key, name, hue] of accents) {
    const s = scales[hue];
    fs.writeFileSync(
      path.join(dir, 'starlight', `${key}.css`),
      `${header(`Starlight accent for ${name} (${hue}).`)}
:root {
  --sl-color-accent-low: ${s[900]};
  --sl-color-accent: ${s[400]};
  --sl-color-accent-high: ${s[200]};
  --sl-color-purple-low: ${s[900]};
  --sl-color-purple: ${s[400]};
  --sl-color-purple-high: ${s[200]};
}

:root[data-theme='light'] {
  --sl-color-accent-low: ${s[100]};
  --sl-color-accent: ${s[700]};
  --sl-color-accent-high: ${s[900]};
  --sl-color-purple-low: ${s[100]};
  --sl-color-purple: ${s[700]};
  --sl-color-purple-high: ${s[900]};
}
`,
    );
  }
}
